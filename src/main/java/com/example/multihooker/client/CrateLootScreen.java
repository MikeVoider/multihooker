package com.example.multihooker.client;

import java.util.ArrayList;
import java.util.List;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.gui.components.Button;
import net.minecraft.client.gui.screens.Screen;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.ItemStack;

/**
 * In-game "Crate Loot" browser: pick a crate on the left and see exactly what it
 * can drop on the right (item, amount range and relative odds), plus that
 * crate's current catch chance.
 *
 * <p>Every item sits in a real vanilla slot (the container/slot sprite) with the
 * same 18px pitch the vanilla inventory uses, so the icons line up in a grid
 * instead of floating next to their labels.
 *
 * <p>The data comes from {@link CrateLootData}, which reads
 * assets/multihooker/crate_loot.json, generated by tools/crategen/gen_resources.py
 * from the same table as the real loot files, so this screen can never drift from
 * what the crates actually give.
 *
 * <p>Below the crate's own drops sits the cross-mod bonus roll: one extra item
 * pulled from the broad conventional item tags, which is where other installed
 * mods' loot shows up. The list scrolls with the mouse wheel when a crate has
 * more rows than the panel fits.
 */
public class CrateLootScreen extends Screen {
   /** The vanilla container slot sprite: drawn 18x18 behind every item. */
   private static final ResourceLocation SLOT_SPRITE = ResourceLocation.withDefaultNamespace("container/slot");

   private static final int PANEL_WIDTH = 384;
   private static final int PANEL_HEIGHT = 268;
   private static final int LEFT_X = 8;
   private static final int LEFT_W = 132;
   private static final int RIGHT_X = 150;
   private static final int RIGHT_W = 224;
   private static final int LIST_TOP = 30;
   private static final int ROW_H = 17;
   /** Slot sprite size and the pitch between stacked entries. */
   private static final int SLOT = 18;
   private static final int ENTRY_TOP = 48;
   private static final int ENTRY_H = SLOT;

   private final Screen parent;
   private int selected;
   /** First visible row of the loot list; the wheel scrolls the rest into view. */
   private int scroll;
   private final List<Button> buttons = new ArrayList<>();
   private List<CrateLootData.Tier> tiers = List.of();

   public CrateLootScreen(Screen parent) {
      super(Component.literal("Trove Loot"));
      this.parent = parent;
   }

   protected void init() {
      this.tiers = CrateLootData.tiers();
      this.buttons.clear();
      int left = (this.width - PANEL_WIDTH) / 2;
      int top = (this.height - PANEL_HEIGHT) / 2;

      for (int i = 0; i < this.tiers.size(); i++) {
         int index = i;
         this.buttons.add(
            this.addRenderableWidget(
               Button.builder(Component.empty(), button -> this.select(index))
                  .bounds(left + LEFT_X, top + LIST_TOP + i * ROW_H, LEFT_W, 16)
                  .build()
            )
         );
      }

      this.addRenderableWidget(
         Button.builder(Component.translatable("gui.done"), button -> this.onClose())
            .bounds(left + LEFT_X, top + PANEL_HEIGHT - 26, LEFT_W, 18)
            .build()
      );
      this.updateLabels();
   }

   private void select(int index) {
      this.selected = index;
      this.scroll = 0;
      this.updateLabels();
   }

   private void updateLabels() {
      for (int i = 0; i < this.buttons.size() && i < this.tiers.size(); i++) {
         String name = Component.translatable("block.multihooker." + this.tiers.get(i).key + "_crate").getString();
         this.buttons.get(i).setMessage(Component.literal((i == this.selected ? "> " : "") + name));
      }
   }

   private static void drawSlot(GuiGraphics graphics, int x, int y) {
      graphics.blitSprite(SLOT_SPRITE, x, y, SLOT, SLOT);
   }

   public void render(GuiGraphics graphics, int mouseX, int mouseY, float partialTick) {
      int left = (this.width - PANEL_WIDTH) / 2;
      int top = (this.height - PANEL_HEIGHT) / 2;
      // Panel first, so the widgets are drawn on top of it instead of under a dark tint.
      graphics.fill(left, top, left + PANEL_WIDTH, top + PANEL_HEIGHT, -871362544);
      graphics.renderOutline(left, top, PANEL_WIDTH, PANEL_HEIGHT, -11184811);
      super.render(graphics, mouseX, mouseY, partialTick);
      graphics.drawCenteredString(this.font, this.title, this.width / 2, top + 8, -10929);
      graphics.drawString(this.font, Component.literal("Odds are per roll"), left + LEFT_X, top + 20, -8355712, false);
      if (this.tiers.isEmpty()) {
         graphics.drawCenteredString(this.font, Component.literal("Trove data unavailable"), this.width / 2, top + 60, -65536);
         return;
      }

      CrateLootData.Tier tier = this.tiers.get(Math.min(this.selected, this.tiers.size() - 1));
      int rx = left + RIGHT_X;
      this.drawSlot(graphics, rx, top + 20);
      graphics.renderItem(tier.crateStack(), rx + 1, top + 21);
      graphics.drawString(
         this.font,
         Component.translatable("block.multihooker." + tier.key + "_crate"),
         rx + SLOT + 6,
         top + 23,
         -10929,
         false
      );
      graphics.drawString(
         this.font,
         Component.literal(
            "Rolls "
               + tier.rollMin
               + "-"
               + tier.rollMax
               + "   "
               + tier.entries.size()
               + " drops   "
               + CrateLootData.formatPercent(CrateLootData.chanceFor(tier.key))
               + " catch"
         ),
         rx + SLOT + 6,
         top + 36,
         -8355712,
         false
      );
      int totalWeight = tier.totalWeight();
      int bonusWeight = tier.bonusTotalWeight();
      // The bonus section only exists when the crate has cross-mod tags to show.
      int bonusRows = tier.bonusEntries.isEmpty() ? 0 : tier.bonusEntries.size() + 1;
      // The book stack is its own pool with its own chance, so it gets its own
      // titled section too - never folded into the main odds.
      int bookRows = tier.bookEntries.isEmpty() ? 0 : tier.bookEntries.size() + 1;
      // Relics are a fourth pool: 0.2% on the Curios slot tags.
      int relicRows = tier.relicEntries.isEmpty() ? 0 : tier.relicEntries.size() + 1;

      // One 18px slot per row, packed from the top. Everything that can be shown
      // counts as a row, including each section's little title, so a crate
      // with more loot than the panel is tall simply scrolls.
      int room = (PANEL_HEIGHT - 4 - ENTRY_TOP) / ENTRY_H;
      int rows = tier.entries.size() + bonusRows + bookRows + relicRows;
      int maxScroll = Math.max(0, rows - room);
      this.scroll = Math.max(0, Math.min(maxScroll, this.scroll));

      if (rows == 0) {
         graphics.drawCenteredString(this.font, Component.literal("No drops defined"), rx + RIGHT_W / 2, top + ENTRY_TOP, -65536);
         return;
      }

      if (maxScroll > 0) {
         graphics.drawString(this.font, Component.literal("scroll ↓"), rx + RIGHT_W - this.font.width("scroll ↓"), top + 20, -8355712, false);
      }

      int last = Math.min(rows, this.scroll + room);

      for (int row = this.scroll; row < last; row++) {
         int y = top + ENTRY_TOP + (row - this.scroll) * ENTRY_H;

         if (row < tier.entries.size()) {
            this.drawEntry(graphics, rx, y, tier.entries.get(row), totalWeight);
         } else if (row < tier.entries.size() + bonusRows) {
            int i = row - tier.entries.size();
            if (i == 0) {
               // The cross-mod bonus roll: its own pool, so its own odds.
               graphics.fill(rx, y - 2, rx + RIGHT_W, y - 1, -11184811);
               graphics.drawString(this.font, Component.literal("Bonus roll: one item from another installed mod"), rx, y + 5, -22016, false);
            } else {
               this.drawEntry(graphics, rx, y, tier.bonusEntries.get(i - 1), bonusWeight);
            }
         } else if (row < tier.entries.size() + bonusRows + bookRows) {
            int i = row - tier.entries.size() - bonusRows;
            if (i == 0) {
               // The book stack: rare, but several at once.
               graphics.fill(rx, y - 2, rx + RIGHT_W, y - 1, -11184811);
               graphics.drawString(this.font, Component.literal("Mystery Books: rare, and a whole stack at once"), rx, y + 5, -22016, false);
            } else {
               this.drawEntry(graphics, rx, y, tier.bookEntries.get(i - 1), 0);
            }
         } else {
            int i = row - tier.entries.size() - bonusRows - bookRows;
            if (i == 0) {
               // Relics: one Curios relic, and only very rarely.
               graphics.fill(rx, y - 2, rx + RIGHT_W, y - 1, -11184811);
               graphics.drawString(this.font, Component.literal("Relics: one Curios relic, once in ~250 troves"), rx, y + 5, -22016, false);
            } else {
               this.drawEntry(graphics, rx, y, tier.relicEntries.get(i - 1), 0);
            }
         }
      }

      if (maxScroll > 0) {
         int trackTop = top + ENTRY_TOP;
         int trackH = room * ENTRY_H;
         int trackX = rx + RIGHT_W + 4;
         graphics.fill(trackX, trackTop, trackX + 3, trackTop + trackH, -11184811);
         int thumbH = Math.max(10, trackH * room / rows);
         int thumbY = trackTop + (trackH - thumbH) * this.scroll / maxScroll;
         graphics.fill(trackX, thumbY, trackX + 3, thumbY + thumbH, -6381922);
      }
   }

   /** One loot row: slot, icon, name and that entry's share of its pool. */
   private void drawEntry(GuiGraphics graphics, int rx, int y, CrateLootData.Entry entry, int totalWeight) {
      this.drawSlot(graphics, rx, y);
      ItemStack stack = entry.stack();
      // Tag entries ("any gem") have no single icon of their own, so the first
      // item of the tag stands in for the whole row instead of an empty slot.
      if (stack.isEmpty() && entry.isTag()) {
         List<ItemStack> tagItems = entry.stacks();
         if (!tagItems.isEmpty()) {
            stack = tagItems.get(0);
         }
      }

      if (!stack.isEmpty()) {
         graphics.renderItem(stack, rx + 1, y + 1);
      }

      graphics.drawString(this.font, Component.literal(entry.label()), rx + SLOT + 6, y + 5, -6497026, false);
      String percent = entry.chancePercent(totalWeight) + "%";
      graphics.drawString(this.font, Component.literal(percent), rx + RIGHT_W - this.font.width(percent), y + 5, -8355712, false);
   }

   @Override
   public boolean mouseScrolled(double mouseX, double mouseY, double scrollX, double scrollY) {
      CrateLootData.Tier tier = this.tier();
      if (tier == null) {
         return super.mouseScrolled(mouseX, mouseY, scrollX, scrollY);
      }

      int room = (PANEL_HEIGHT - 4 - ENTRY_TOP) / ENTRY_H;
      int rows = tier.entries.size()
         + (tier.bonusEntries.isEmpty() ? 0 : tier.bonusEntries.size() + 1)
         + (tier.bookEntries.isEmpty() ? 0 : tier.bookEntries.size() + 1)
         + (tier.relicEntries.isEmpty() ? 0 : tier.relicEntries.size() + 1);
      int maxScroll = Math.max(0, rows - room);
      if (maxScroll <= 0) {
         return super.mouseScrolled(mouseX, mouseY, scrollX, scrollY);
      }

      this.scroll = Math.max(0, Math.min(maxScroll, this.scroll - (int)Math.signum(scrollY)));
      return true;
   }

   /** The crate the right-hand panel is currently showing, or null when the data failed to load. */
   private CrateLootData.Tier tier() {
      return this.tiers.isEmpty() ? null : this.tiers.get(Math.min(this.selected, this.tiers.size() - 1));
   }

   public void onClose() {
      if (this.minecraft != null) {
         this.minecraft.setScreen(this.parent);
      }
   }

   public boolean isPauseScreen() {
      return false;
   }
}
